export function translate(
  lang: Language,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = translations[lang]?.[key] ?? de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}

